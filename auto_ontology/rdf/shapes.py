"""The ``ao`` shape sheet: SHACL for the Direct-Mapping vocabulary, generated from
upstream's SQLAlchemy metadata (the same source as ``vocab.py`` and ``export.py``).

    uv run python -m auto_ontology.rdf.shapes > nidra/ao.shapes.ttl

What it states, per table class ``urn:ao:<table>``:

* a scalar column ``urn:ao:<table>#<column>`` has at most one value (``sh:maxCount 1``)
  and the datatype ``client.lit`` writes for it; it is a *functional* property, so a
  writer's ``set`` is the right op (last writer wins);
* an array/JSON column is written twice by ``export.py`` (the whole value as an
  ``rdf:JSON`` literal and one triple per member), so it has no ``maxCount`` and no
  datatype: a *set-valued* property, ``add``/``remove`` (add wins);
* a foreign key column also carries ``urn:ao:<table>#ref-<column>`` with the referenced
  row as object (``sh:class`` the referenced table, at most one).

What it does not state: ``sh:minCount``. The ledger's contract gate is stateless (it sees
only the subjects a request leaves behind, COMMIT-API §6), so a required-ness rule would
refuse every partial write (a rename sets one property). Required columns are listed in
a comment on the shape instead; the engine's own ports keep them.
"""
from __future__ import annotations

import sys

from sqlalchemy import ARRAY, JSON, Boolean, DateTime, Float, Integer, Numeric
from sqlalchemy.dialects.postgresql import JSONB

from auto_ontology.dal.schema import METADATA
from auto_ontology.rdf.vocab import BASE, XSD, class_iri, prop_iri, ref_iri

PREFIXES = f"""@prefix sh: <http://www.w3.org/ns/shacl#> .
@prefix xsd: <{XSD}> .
@prefix rdf: <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
@prefix ao: <{BASE}> .
@prefix aosh: <{BASE}shape/> .
"""


def xsd_datatype(column_type: object) -> str | None:
    """The datatype ``client.lit`` gives a value of this column; None for set-valued."""
    if isinstance(column_type, (ARRAY, JSON, JSONB)):
        return None
    if isinstance(column_type, Boolean):
        return "xsd:boolean"
    if isinstance(column_type, Integer):
        return "xsd:integer"
    if isinstance(column_type, (Float, Numeric)):
        return "xsd:double"
    if isinstance(column_type, DateTime):
        return "xsd:dateTime"
    return "xsd:string"


def shape_for(table_name: str) -> str:
    table = METADATA.tables[table_name]
    fk_by_col = {fk.parent.name: fk.column.table.name for fk in table.foreign_keys}
    required = [c.name for c in table.columns if not c.nullable and c.server_default is None and c.default is None]
    lines = [
        f"aosh:{table_name} a sh:NodeShape ;",
        f"    sh:targetClass <{class_iri(table_name)}> ;",
        f'    rdfs:comment "Direct Mapping of upstream table {table_name}; required columns (kept by the engine, not the gate): {", ".join(required) or "none"}" ;',
    ]
    props = []
    for column in table.columns:
        datatype = xsd_datatype(column.type)
        if datatype is None:
            props.append(
                f"    sh:property [ sh:path <{prop_iri(table_name, column.name)}> ; "
                f'rdfs:comment "set-valued: the whole value as rdf:JSON and one triple per member (add wins)" ]'
            )
        else:
            props.append(
                f"    sh:property [ sh:path <{prop_iri(table_name, column.name)}> ; sh:maxCount 1 ; sh:datatype {datatype} ]"
            )
        if column.name in fk_by_col:
            props.append(
                f"    sh:property [ sh:path <{ref_iri(table_name, column.name)}> ; sh:maxCount 1 ; "
                f"sh:nodeKind sh:IRI ; sh:class <{class_iri(fk_by_col[column.name])}> ]"
            )
    lines.append(" ;\n".join(props) + " .")
    return "\n".join(lines)


def sheet() -> str:
    body = "\n\n".join(shape_for(name) for name in sorted(METADATA.tables))
    return f"{PREFIXES}\n# The ao shape sheet, generated by auto_ontology.rdf.shapes from dal/schema.py ({len(METADATA.tables)} tables).\n\n{body}\n"


def main(argv: list[str]) -> int:
    sys.stdout.write(sheet())
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
